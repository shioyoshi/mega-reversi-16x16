export function createInitialGameState(profile: UserProfile): GameState {
  const estimated = estimateInitialStats(profile);
  return {
    profile,
    muscleStats: estimated.muscleStats,
    totalMuscleExp: 0,
    lifetimeMuscleExp: 0,
    playerLevel: 1,
    totalReps: 0,
    totalLiftedKg: 0,
    fatigue: 0,
    pumpGauge: 0,
    isPumpMode: false,
    pumpTimeRemaining: 0,
    hasGymMembership: false,
    exercises: initialExercises.map((e) => ({ ...e })),
    upgrades: initialUpgrades.map((u) => ({ ...u })),
    achievements: initialAchievements.map((a) => ({ ...a })),
    lastSavedTimestamp: Date.now(),
  };
}
